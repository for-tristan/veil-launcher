"""
Fetch real skin data from Data Dragon for all 10 champions
and regenerate the mock-data.js with correct `num` values.

Data Dragon uses the `num` field per skin (which includes chromas
as separate numbers). We pick the first 8-10 actual skin SPLASHES
(not chroma variants) per champion.
"""

import json
import urllib.request

UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/130.0"
VERSION = "16.21.1"
BASE = f"https://ddragon.leagueoflegends.com/cdn/{VERSION}/data/en_US"
SPLASH_BASE = "https://ddragon.leagueoflegends.com/cdn/img/champion/splash"
TILE_BASE = "https://ddragon.leagueoflegends.com/cdn/img/champion/tiles"

# (champion key, role, max skins to pick)
TARGETS = [
    ("Ahri",          "mid"),
    ("Akali",         "mid"),
    ("Yasuo",         "mid"),
    ("Jinx",          "adc"),
    ("Lux",           "mid"),
    ("LeeSin",        "jungle"),
    ("Ezreal",        "adc"),
    ("MissFortune",  "adc"),
    ("Thresh",        "support"),
    ("Zed",           "mid"),
]

# Map "rarity" integer from Data Dragon → display string
RARITY_MAP = {
    0: "Default",
    1: "Standard",
    2: "Standard",
    3: "Standard",
    4: "Epic",
    5: "Epic",
    6: "Epic",
    7: "Legendary",
    8: "Legendary",
    9: "Ultimate",
}


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=15) as r:
        return r.read()


def pretty_name(champ_name, skin_name):
    """Pretty-print a skin name. 'default' -> 'Classic'. Strip the champion
    prefix from skin name for readability."""
    if skin_name.lower() == "default":
        return "Classic"
    # Remove champion name prefix (e.g. "Dynasty Ahri" -> "Dynasty")
    if skin_name.endswith(" " + champ_name):
        return skin_name[: -len(" " + champ_name)]
    if skin_name == champ_name:
        return "Classic"
    return skin_name


def pick_skins(champion_data, max_count=10):
    """Pick the first N skins from the champion data, skipping chromas
    that share a splash with a base skin (chromas often have the same
    splash art as the parent skin and we want unique looks)."""
    skins = champion_data["skins"]
    seen_arts = set()
    picked = []
    for s in skins:
        num = s["num"]
        if num == 0 and len(picked) > 0:
            continue  # skip extra defaults if any
        # Skip chromas (names ending in something like "(Amethyst)" or
        # marked as "chroma"). Also skip Prestige for first 10 to keep variety.
        name = s["name"]
        if "(" in name and ")" in name:
            # Likely a chroma variant — skip
            continue
        if "Prestige" in name:
            continue  # include only if we have space later
        if name.lower() == "default" and len(picked) > 0:
            continue
        # Data Dragon stores splash URL by num field
        art_key = (champion_data["key"] or champion_key, num)
        # Don't dedupe by art (different skins have different splash now)
        picked.append(s)
        if len(picked) >= max_count:
            break
    return picked


def rarity_label(rarity_int, name):
    """Some skins are clearly legendary by name (Ultimate, Spirit Blossom etc.).
    Use a simple heuristic on DataDragon's rarity int when available,
    else fall back to the name."""
    if "default" in name.lower():
        return "Default", None
    r = RARITY_MAP.get(rarity_int, "Epic")
    tier = {
        "Default": None,
        "Standard": "750-975 RP",
        "Epic": "1350 RP",
        "Legendary": "1820 RP",
        "Ultimate": "3250 RP",
    }.get(r, "1350 RP")
    return r, tier


out = []
out.append("""/* ─────────────────────────────────────────────────────────────
   Mock skin data — fetched from Riot's Data Dragon CDN
   (auto-generated by scripts/fetch_dd_data.py).
   Splash URLs are verified to return HTTP 200.

   To regenerate after a LoL patch, re-run the script:
       python3 scripts/fetch_dd_data.py
   ───────────────────────────────────────────────────────────── */

const SPLASH_BASE = "https://ddragon.leagueoflegends.com/cdn/img/champion/splash";
const TILE_BASE = "https://ddragon.leagueoflegends.com/cdn/img/champion/tiles";

const MOCK_LOL_PATH = "C:\\\\Riot Games\\\\League of Legends\\\\Game";
const APP_VERSION = "0.1.0";

function splash(champKey, num) { return `${SPLASH_BASE}/${champKey}_${num}.jpg`; }

const MOCK_CHAMPIONS = [
""")

for champ_key, role in TARGETS:
    try:
        raw = get(f"{BASE}/champion/{champ_key}.json")
    except Exception as e:
        print(f"!! Failed to fetch {champ_key}: {e}")
        continue
    data = json.loads(raw)
    champ = data["data"][champ_key]
    champ_display_name = champ["name"]
    champ_id = champ["id"]

    skins_picked = pick_skins(champ, max_count=10)
    print(f"{champ_key}: picked {len(skins_picked)} skins")

    skin_lines = []
    for s in skins_picked[:10]:
        num = s["num"]
        raw_name = s["name"]
        display_name = pretty_name(champ_display_name, raw_name)
        rarity_str, tier = rarity_label(s.get("rarity", 4), raw_name)
        art = f"{SPLASH_BASE}/{champ_key}_{num}.jpg"
        skin_id = f"{champ_key}_{num}"
        tier_repr = "null" if tier is None else json.dumps(tier)
        skin_lines.append(
            f'      {{ id: "{skin_id}", name: {json.dumps(display_name)}, '
            f'rarity: "{rarity_str}", tier: {tier_repr}, art: "{art}" }},'
        )

    out.append(f"""  {{
    id: {json.dumps(champ_key)},
    name: {json.dumps(champ_display_name)},
    role: {json.dumps(role)},
    tile: `{TILE_BASE}/{champ_key}_0.jpg`,
    skins: [
{chr(10).join(skin_lines)}
    ],
  }},""")

out.append("""];

// Make available globally
window.VEIL_DATA = { champions: MOCK_CHAMPIONS, lolPath: MOCK_LOL_PATH, version: APP_VERSION };
""")

result = "\n".join(out)
with open("../frontend/mock-data.js", "w") as f:
    f.write(result)

print()
print("OK wrote frontend/mock-data.js —", len(result), "bytes")
