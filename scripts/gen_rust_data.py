"""Generate src-tauri/src/skin_data.rs from the same Data Dragon data
used to generate frontend/mock-data.js. Keeps the Rust mock backend
in sync with the frontend mock data."""

import json
import urllib.request

UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/130.0"
VERSION = "16.21.1"
BASE = f"https://ddragon.leagueoflegends.com/cdn/{VERSION}/data/en_US"

TARGETS = [
    ("Ahri",          "mid"),
    ("Akali",         "mid"),
    ("Yasuo",         "mid"),
    ("Jinx",          "adc"),
    ("Lux",           "mid"),
    ("LeeSin",        "jungle"),
    ("Ezreal",        "adc"),
    ("MissFortune",  "adc"),
    ("Thresh",        "support"),
    ("Zed",           "mid"),
]

RARITY_MAP = {
    0: "Default", 1: "Standard", 2: "Standard", 3: "Standard",
    4: "Epic", 5: "Epic", 6: "Epic",
    7: "Legendary", 8: "Legendary", 9: "Ultimate",
}


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=15) as r:
        return r.read()


def pretty_name(champ_name, skin_name):
    if skin_name.lower() == "default":
        return "Classic"
    if skin_name.endswith(" " + champ_name):
        return skin_name[: -len(" " + champ_name)]
    if skin_name == champ_name:
        return "Classic"
    return skin_name


def pick_skins(champion_data, max_count=10):
    skins = champion_data["skins"]
    picked = []
    for s in skins:
        num = s["num"]
        if num == 0 and len(picked) > 0:
            continue
        name = s["name"]
        if "(" in name and ")" in name:
            continue
        if "Prestige" in name:
            continue
        if name.lower() == "default" and len(picked) > 0:
            continue
        picked.append(s)
        if len(picked) >= max_count:
            break
    return picked


def rarity_label(rarity_int, name):
    if "default" in name.lower():
        return "Default", None
    r = RARITY_MAP.get(rarity_int, "Epic")
    tier = {
        "Default": None,
        "Standard": "750-975 RP",
        "Epic": "1350 RP",
        "Legendary": "1820 RP",
        "Ultimate": "3250 RP",
    }.get(r, "1350 RP")
    return r, tier


def rust_str(s: str) -> str:
    """Rust string literal with proper escaping."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


# Fetch all data first
champions_data = []
for champ_key, role in TARGETS:
    raw = get(f"{BASE}/champion/{champ_key}.json")
    data = json.loads(raw)
    champ = data["data"][champ_key]
    skins = pick_skins(champ, max_count=10)
    champions_data.append((champ_key, champ["name"], role, skins))
    print(f"{champ_key}: picked {len(skins)} skins")

# Write the Rust file
out = []
out.append("// Auto-generated by scripts/gen_rust_data.py")
out.append("// Data Dragon version: " + VERSION)
out.append("//")
out.append("// Static champion + skin catalog served by the launcher.")
out.append("// Mirrors the browser-side mock data in `frontend/mock-data.js`.")
out.append("//")
out.append("// In a production build, you'd fetch this from Data Dragon instead:")
out.append("//   https://ddragon.leagueoflegends.com/cdn/<version>/data/en_US/champion.json")
out.append("// For the prototype, hardcoding keeps the binary lean & offline-friendly.")
out.append("")
out.append("use crate::{Champion, Skin};")
out.append("")
out.append("fn splash(champ: &str, n: u32) -> String {")
out.append('    format!(')
out.append('        "https://ddragon.leagueoflegends.com/cdn/img/champion/splash/{}_{}.jpg",')
out.append('        champ, n')
out.append('    )')
out.append('}')
out.append("")
out.append("fn tile(champ: &str) -> String {")
out.append('    format!(')
out.append('        "https://ddragon.leagueoflegends.com/cdn/img/champion/tiles/{}_0.jpg",')
out.append('        champ')
out.append('    )')
out.append('}')
out.append("")
out.append("#[rustfmt::skip]")
out.append("pub fn champions() -> Vec<Champion> {")
out.append("    vec![")

for champ_key, champ_display_name, role, skins in champions_data:
    out.append("        Champion {")
    out.append(f"            id: {rust_str(champ_key)}.into(),")
    out.append(f"            name: {rust_str(champ_display_name)}.into(),")
    out.append(f"            role: {rust_str(role)}.into(),")
    out.append(f"            tile: tile({rust_str(champ_key)}),")
    out.append("            skins: vec![")
    for s in skins[:10]:
        num = s["num"]
        display_name = pretty_name(champ_display_name, s["name"])
        rarity_str, tier = rarity_label(s.get("rarity", 4), s["name"])
        skin_id = f"{champ_key}_{num}"
        if tier is None:
            tier_repr = "None"
        else:
            tier_repr = f"Some({rust_str(tier)}.into())"
        out.append(
            f"                Skin {{ id: {rust_str(skin_id)}.into(), name: {rust_str(display_name)}.into(), "
            f"rarity: {rust_str(rarity_str)}.into(), tier: {tier_repr}, art: splash({rust_str(champ_key)}, {num}) }},"
        )
    out.append("            ],")
    out.append("        },")

out.append("    ]")
out.append("}")
out.append("")

result = "\n".join(out)
with open("../src-tauri/src/skin_data.rs", "w") as f:
    f.write(result)

print()
print("OK wrote src-tauri/src/skin_data.rs —", len(result), "bytes")
